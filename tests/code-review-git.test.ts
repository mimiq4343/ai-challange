import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, mkdir, readFile, rename, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { collectReviewSnapshot, fetchReviewHead, loadReviewCorpus } from "../src/lib/code-review-git";

test("PR snapshots use the merge base and immutable blobs, including additions, deletions and renames", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "flash-review-git-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = (...args: string[]) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();
  git("init", "-q", "-b", "main");
  git("config", "user.email", "test@example.com");
  git("config", "user.name", "Test");
  await mkdir(join(root, "src"));
  await mkdir(join(root, "docs"));
  await writeFile(join(root, "README.md"), "# Flash\n");
  await writeFile(join(root, "docs/storage.md"), "# Storage\nAtomic exchange.\n");
  await writeFile(join(root, "src/chat.ts"), "export const answer = 1;\n");
  await writeFile(join(root, "src/old name.tsx"), "export const Old = () => <p>Old</p>;\n");
  await writeFile(join(root, "src/deleted.ts"), "export const gone = true;\n");
  git("add", "."); git("commit", "-qm", "base");
  const ancestor = git("rev-parse", "HEAD");
  git("switch", "-qc", "feature");
  await writeFile(join(root, "src/chat.ts"), "export const answer = 2;\n");
  await writeFile(join(root, "src/new.ts"), "export const fresh = true;\n");
  await rename(join(root, "src/old name.tsx"), join(root, "src/new name.tsx"));
  await rm(join(root, "src/deleted.ts"));
  await writeFile(join(root, ".env.local"), "PRIVATE_FIXTURE=must-not-leak\n");
  await writeFile(join(root, "binary.png"), Buffer.from([0, 1, 2]));
  await symlink("/etc/passwd", join(root, "src/link.ts"));
  git("add", "."); git("commit", "-qm", "feature");
  const head = git("rev-parse", "HEAD");
  git("switch", "-q", "main");
  await writeFile(join(root, "src/main-only.ts"), "export const unrelated = true;\n");
  git("add", "."); git("commit", "-qm", "advance main");
  const base = git("rev-parse", "HEAD");
  await writeFile(join(root, "src/chat.ts"), "uncommitted text must not appear\n");

  const snapshot = await collectReviewSnapshot(root, base, head);
  assert.equal(snapshot.mergeBaseSha, ancestor);
  assert.equal(snapshot.headSha, head);
  assert.equal(snapshot.totalFiles, 7);
  assert.equal(snapshot.files.length, 4);
  assert.equal(snapshot.files.find((file) => file.path === "src/chat.ts")?.content, "export const answer = 2;\n");
  assert.match(snapshot.files.find((file) => file.path === "src/new.ts")!.patch, /\+export const fresh/);
  assert.equal(snapshot.files.find((file) => file.path === "src/deleted.ts")?.side, "base");
  assert.equal(snapshot.files.find((file) => file.path === "src/deleted.ts")?.content, "export const gone = true;\n");
  assert.equal(snapshot.files.find((file) => file.path === "src/new name.tsx")?.previousPath, "src/old name.tsx");
  assert.equal(snapshot.files.some((file) => file.path === "src/main-only.ts"), false);
  assert.equal(snapshot.skipped.length, 3);
  assert.equal(JSON.stringify(snapshot).includes("must-not-leak"), false);
  assert.equal(await readFile(join(root, "src/chat.ts"), "utf8"), "uncommitted text must not appear\n");

  const corpus = await loadReviewCorpus(root, base);
  assert.equal(corpus.find((file) => file.source === "src/chat.ts")?.text, "export const answer = 1;\n");
  assert.ok(corpus.some((file) => file.source === "src/old name.tsx"));
  assert.ok(corpus.some((file) => file.source === "docs/storage.md"));
  assert.equal(corpus.some((file) => file.source === ".env.local"), false);
  git("update-ref", "refs/pull/32/head", head);
  git("remote", "add", "origin", root);
  await fetchReviewHead(root, 32, head, "fixture-token");
  assert.equal(git("rev-parse", "HEAD"), base);
  assert.equal(await readFile(join(root, "src/chat.ts"), "utf8"), "uncommitted text must not appear\n");
  git("update-ref", "refs/pull/32/head", base);
  await assert.rejects(fetchReviewHead(root, 32, head, "fixture-token"), /PR уже изменился/);
  await assert.rejects(collectReviewSnapshot(root, "HEAD", head), /SHA/);
  await assert.rejects(collectReviewSnapshot(root, base, "--output=oops"), /SHA/);
});

test("oversized and binary source files are reported instead of silently truncating their review", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "flash-review-limits-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = (...args: string[]) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();
  git("init", "-q"); git("config", "user.email", "test@example.com"); git("config", "user.name", "Test");
  await writeFile(join(root, "README.md"), "# Base\n");
  git("add", "."); git("commit", "-qm", "base");
  const base = git("rev-parse", "HEAD");
  await writeFile(join(root, "large.ts"), "x".repeat(200_001));
  await writeFile(join(root, "binary.ts"), Buffer.from([0, 255, 12]));
  git("add", "."); git("commit", "-qm", "large files");
  const snapshot = await collectReviewSnapshot(root, base, git("rev-parse", "HEAD"));
  assert.equal(snapshot.files.length, 0);
  assert.deepEqual(snapshot.skipped.map((file) => file.path).sort(), ["binary.ts", "large.ts"]);
  assert.match(snapshot.skipped.find((file) => file.path === "large.ts")!.reason, /лимит/);
  assert.match(snapshot.skipped.find((file) => file.path === "binary.ts")!.reason, /бинарн|UTF-8/);
});

test("deletion-only hunks can anchor a review to surviving head code or the removed base content", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "flash-review-deletion-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const git = (...args: string[]) => execFileSync("git", ["-C", root, ...args], { encoding: "utf8" }).trim();
  git("init", "-q"); git("config", "user.email", "test@example.com"); git("config", "user.name", "Test");
  const original = 'function privateData(user) {\n  if (!user.admin) throw new Error("forbidden");\n  return secrets;\n}\n';
  await writeFile(join(root, "guard.ts"), original);
  await writeFile(join(root, "empty.ts"), "export const required = true;\n");
  await writeFile(join(root, "tail.ts"), "allowed();\nverifyAdmin();\n");
  git("add", "."); git("commit", "-qm", "base");
  const base = git("rev-parse", "HEAD");
  await writeFile(join(root, "guard.ts"), "function privateData(user) {\n  return secrets;\n}\n");
  await writeFile(join(root, "empty.ts"), "");
  await writeFile(join(root, "tail.ts"), "allowed();\n");
  git("add", "."); git("commit", "-qm", "remove guards");
  const snapshot = await collectReviewSnapshot(root, base, git("rev-parse", "HEAD"));
  const guard = snapshot.files.find((file) => file.path === "guard.ts")!;
  assert.deepEqual(guard.changedLines, [2]);
  assert.equal(guard.side, "head");
  const emptied = snapshot.files.find((file) => file.path === "empty.ts")!;
  assert.equal(emptied.side, "base");
  assert.equal(emptied.content, "export const required = true;\n");
  assert.deepEqual(emptied.changedLines, [1]);
  assert.deepEqual(snapshot.files.find((file) => file.path === "tail.ts")!.changedLines, [1]);
});
